"""Abstract LLM Provider interface for HARNESS.

Isolates external model providers (LiteLLM, OpenAI, Anthropic, Gemini).
The core domain never imports third-party provider SDKs directly (RNF-12).
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Any

from harness_agent.core.entities import Message, TokenUsage, ToolCall


@dataclass(frozen=True)
class ToolDefinition:
    """Canonical declaration of a tool exposed to the model.

    Attributes:
        name: Unique tool identifier.
        description: Functional description for the language model.
        parameters: JSON Schema defining expected arguments.
    """

    name: str
    description: str
    parameters: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class ProviderResponse:
    """Standardized response produced by a Provider.complete invocation.

    Attributes:
        content: Textual response generated by the model.
        tool_calls: List or tuple of tool invocations requested by the model.
        usage: Token consumption metrics reported by the provider.
    """

    content: str = ""
    tool_calls: list[ToolCall] = field(default_factory=list)
    usage: TokenUsage | None = None


class Provider(ABC):
    """Abstract Base Class for LLM providers.

    All model interaction adapters must implement this contract.
    Firmas asíncronas son provisionales sujetas a SPK-02.
    """

    @abstractmethod
    async def complete(
        self,
        messages: list[Message],
        tools: list[ToolDefinition] | None = None,
    ) -> ProviderResponse:
        """Execute a completion call against the language model.

        Args:
            messages: Ordered sequence of messages representing the context window.
            tools: Optional list of tools declared for tool calling.

        Returns:
            ProviderResponse containing text, tool calls, and token usage.
        """
        ...
